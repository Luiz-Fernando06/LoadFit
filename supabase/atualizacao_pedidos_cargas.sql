-- ------------------------------------------------------------
-- PEDIDOS
-- ------------------------------------------------------------
create table if not exists public.pedidos (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid()
        references auth.users(id) on delete cascade,
    cliente_id bigint not null
        references public.clientes(id) on delete restrict,
    data_prevista date not null,
    observacao text not null default '',
    peso_total numeric(12,2) not null default 0 check (peso_total >= 0),
    status text not null default 'PENDENTE',
    criado_em timestamptz not null default now()
);

create index if not exists pedidos_user_id_idx on public.pedidos(user_id);
create index if not exists pedidos_cliente_id_idx on public.pedidos(cliente_id);
create index if not exists pedidos_status_idx on public.pedidos(user_id, status);

alter table public.pedidos enable row level security;
grant select, insert, update, delete on table public.pedidos to authenticated;
do $$ begin
    if to_regclass('public.pedidos_id_seq') is not null then
        execute 'grant usage, select on sequence public.pedidos_id_seq to authenticated';
    end if;
end $$;

drop policy if exists "Usuario visualiza seus pedidos" on public.pedidos;
create policy "Usuario visualiza seus pedidos" on public.pedidos
for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "Usuario cadastra seus pedidos" on public.pedidos;
create policy "Usuario cadastra seus pedidos" on public.pedidos
for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists "Usuario altera seus pedidos" on public.pedidos;
create policy "Usuario altera seus pedidos" on public.pedidos
for update to authenticated using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists "Usuario exclui seus pedidos" on public.pedidos;
create policy "Usuario exclui seus pedidos" on public.pedidos
for delete to authenticated using ((select auth.uid()) = user_id);


