on public.usuarios for select to authenticated
using ((select auth.uid()) = id);

drop policy if exists "Usuario altera seu perfil" on public.usuarios;
create policy "Usuario altera seu perfil"
on public.usuarios for update to authenticated
using ((select auth.uid()) = id)
with check ((select auth.uid()) = id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
    insert into public.usuarios (id, nome, email)
    values (
        new.id,
        coalesce(new.raw_user_meta_data ->> 'nome', ''),
        coalesce(new.email, '')
    )
    on conflict (id) do update
    set nome = excluded.nome,
        email = excluded.email;
    return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- Preenche perfis de contas que ja existiam antes deste trigger.
insert into public.usuarios (id, nome, email, criado_em)
select id, coalesce(raw_user_meta_data ->> 'nome', ''), coalesce(email, ''), created_at
from auth.users
on conflict (id) do update
set nome = excluded.nome, email = excluded.email;


