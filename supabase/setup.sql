-- ------------------------------------------------------------
-- VALIDACAO: impede vincular registros de outro usuario.
-- ------------------------------------------------------------
create or replace function public.validar_vinculos_loadfit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    if tg_table_name = 'pedidos' then
        if not exists (
            select 1 from public.clientes c
            where c.id = new.cliente_id and c.user_id = new.user_id
        ) then
            raise exception 'O cliente selecionado nao pertence a este usuario.';
        end if;
    elsif tg_table_name = 'pedido_itens' then
        if not exists (
            select 1 from public.pedidos p
            where p.id = new.pedido_id and p.user_id = new.user_id
        ) then
            raise exception 'O pedido selecionado nao pertence a este usuario.';
        end if;
        if not exists (
            select 1 from public.materiais m
            where m.id = new.material_id and m.user_id = new.user_id
        ) then
            raise exception 'O material selecionado nao pertence a este usuario.';
        end if;
    elsif tg_table_name = 'cargas' then
        if not exists (
            select 1 from public.caminhoes c
            where c.id = new.caminhao_id and c.user_id = new.user_id
        ) then
            raise exception 'O caminhao selecionado nao pertence a este usuario.';
        end if;
        if not exists (
            select 1 from public.motoristas m
            where m.id = new.motorista_id and m.user_id = new.user_id
        ) then
            raise exception 'O motorista selecionado nao pertence a este usuario.';
        end if;
    elsif tg_table_name = 'carga_pedidos' then
        if not exists (
            select 1 from public.cargas c
            where c.id = new.carga_id and c.user_id = new.user_id
        ) then
            raise exception 'A carga selecionada nao pertence a este usuario.';
        end if;
        if not exists (
            select 1 from public.pedidos p
            where p.id = new.pedido_id and p.user_id = new.user_id
              and p.status = 'PENDENTE'
        ) then
            raise exception 'O pedido nao esta pendente ou nao pertence a este usuario.';
        end if;
    end if;
    return new;
end;
$$;

drop trigger if exists validar_cliente_pedido_loadfit on public.pedidos;
create trigger validar_cliente_pedido_loadfit
before insert or update on public.pedidos
for each row execute procedure public.validar_vinculos_loadfit();

drop trigger if exists validar_item_pedido_loadfit on public.pedido_itens;
create trigger validar_item_pedido_loadfit
before insert or update on public.pedido_itens
for each row execute procedure public.validar_vinculos_loadfit();

