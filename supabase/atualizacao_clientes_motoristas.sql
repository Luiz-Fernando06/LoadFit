-- ------------------------------------------------------------
-- TABELA: CLIENTES
-- ------------------------------------------------------------
create table if not exists public.clientes (
    id bigint generated by default as identity primary key,
    user_id uuid not null default auth.uid()
        references auth.users(id) on delete cascade,
    nome text not null,
    endereco text not null,
    cidade text not null,
    estado varchar(2) not null,
    criado_em timestamptz not null default now()
);

create index if not exists clientes_user_id_idx
on public.clientes(user_id);

alter table public.clientes enable row level security;

grant select, insert, update, delete
on table public.clientes to authenticated;

do $$
begin
    if to_regclass('public.clientes_id_seq') is not null then
        execute 'grant usage, select on sequence public.clientes_id_seq to authenticated';
    end if;
end;
$$;

drop policy if exists "Usuario visualiza seus clientes" on public.clientes;
create policy "Usuario visualiza seus clientes"
on public.clientes for select to authenticated
using ((select auth.uid()) = user_id);

drop policy if exists "Usuario cadastra seus clientes" on public.clientes;
create policy "Usuario cadastra seus clientes"
on public.clientes for insert to authenticated
with check ((select auth.uid()) = user_id);

drop policy if exists "Usuario altera seus clientes" on public.clientes;
create policy "Usuario altera seus clientes"
on public.clientes for update to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

drop policy if exists "Usuario exclui seus clientes" on public.clientes;
create policy "Usuario exclui seus clientes"
on public.clientes for delete to authenticated
using ((select auth.uid()) = user_id);


